def load_bucket_df(cfg: PipelineConfig, bucket_key: str, cache_dir: Path) -> Tuple[pd.DataFrame, Dict[str,int]]:
    rows = []
    stats = {"raw_rows":0, "dropped_no_date":0}
    out_path = cache_dir / f"stage0_raw_{bucket_key}.csv"
    if out_path.exists() and cfg.RESUME:
        try:
            df = pd.read_csv(out_path, dtype=str)
            df["_dt"] = pd.to_datetime(df["_dt"], errors="coerce")
            return df, stats
        except Exception:
            out_path.unlink(missing_ok=True)

    for _name, h in iter_input_sources(cfg.CSV_PATH):
        for chunk in read_csv_chunks(h, cfg.READ_CHUNKSIZE, usecols=None):
            stats["raw_rows"] += len(chunk)
            for c in REQUIRED_COLS:
                if c not in chunk.columns:
                    chunk[c] = ""
            dts = pd.to_datetime(chunk["date"], errors="coerce", utc=True)
            miss = dts.isna()
            if miss.any():
                dts_miss = pd.to_datetime(chunk.loc[miss, "date"], errors="coerce")
                try:
                    if getattr(dts_miss.dt, "tz", None) is None:
                        dts_miss = dts_miss.dt.tz_localize(KST).dt.tz_convert("UTC")
                    else:
                        dts_miss = dts_miss.dt.tz_convert("UTC")
                except Exception:
                    dts_miss = pd.to_datetime(chunk.loc[miss, "date"], errors="coerce", utc=True)
                dts_miss = pd.to_datetime(dts_miss, errors="coerce", utc=True)
                dts.loc[miss] = dts_miss

            keep_mask = []
            dt_keep = []
            for v in dts:
                if pd.isna(v):
                    keep_mask.append(False)
                    stats["dropped_no_date"] += 1
                    dt_keep.append(pd.NaT)
                    continue
                ts = v.tz_convert(KST) if v.tzinfo is not None else v.tz_localize(KST)
                b = bucket_key_from_dt(ts, cfg.BUCKET)
                ok = (b == bucket_key)
                keep_mask.append(ok)
                dt_keep.append(ts)
            if not any(keep_mask):
                continue

            sub = chunk.loc[keep_mask, REQUIRED_COLS].copy()
            sub["_dt"] = [dt_keep[i] for i, ok in enumerate(keep_mask) if ok]
            sub["domain"] = sub["url"].astype(str).apply(safe_domain)
            rows.append(sub)

            if sum(len(x) for x in rows) >= cfg.MAX_DOCS_PER_BUCKET:
                break

    df = pd.concat(rows, ignore_index=True) if rows else pd.DataFrame(columns=REQUIRED_COLS + ["_dt","domain"])
    df.to_csv(out_path, index=False, encoding="utf-8-sig")
    return df, stats

