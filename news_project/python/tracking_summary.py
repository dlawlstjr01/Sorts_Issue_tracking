def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    if _HAVE_TORCH:
        try:
            torch.manual_seed(seed)
            if torch.cuda.is_available():
                torch.cuda.manual_seed_all(seed)
        except Exception:
            pass

def get_device(device: str) -> "torch.device":
    if device == "cpu":
        return torch.device("cpu")
    if device == "cuda":
        return torch.device("cuda")
    return torch.device("cuda" if torch.cuda.is_available() else "cpu")

class KoE5Embedder:
    def __init__(self, model_name: str, device: "torch.device", max_length: int = 512):
        self.device = device
        self.tok = AutoTokenizer.from_pretrained(model_name)
        self.model = AutoModel.from_pretrained(model_name).to(device)
        self.model.eval()
        self.max_length = max_length

    @staticmethod
    def _mean_pool(last_hidden, attn_mask):
        mask = attn_mask.unsqueeze(-1).expand(last_hidden.size()).float()
        return (last_hidden * mask).sum(1) / mask.sum(1).clamp(min=1e-9)

    def encode(self, texts: List[str], batch_size: int = 32) -> np.ndarray:
        outs = []
        for i in tqdm(range(0, len(texts), batch_size), desc="embed", leave=False):
            batch = texts[i:i+batch_size]
            enc = self.tok(batch, padding=True, truncation=True, max_length=self.max_length, return_tensors="pt").to(self.device)
            with torch.no_grad():
                out = self.model(**enc)
                emb = self._mean_pool(out.last_hidden_state, enc["attention_mask"])
                emb = torch.nn.functional.normalize(emb, p=2, dim=1)
            outs.append(emb.detach().cpu().numpy())
        return np.vstack(outs).astype(np.float32)

