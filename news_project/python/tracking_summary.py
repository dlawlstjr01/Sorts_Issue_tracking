def is_noise_keyword(tok: str) -> bool:
    t = (tok or "").strip().lower()
    if len(t) < 2:
        return True
    if t.isdigit():
        return True
    if t in KEYWORD_STOPWORDS:
        return True
    return False

def _strip_kw_particle(tok: str) -> str:
    t = (tok or "").strip().lower()
    if not t:
        return ""
    # Strip one or two trailing particles (e.g., "대통령은" -> "대통령").
    for _ in range(2):
        nt = KW_PARTICLE_RE.sub("", t)
        if nt == t:
            break
        t = nt
    return t

def normalize_keyword_candidate(term: str, max_tokens: int = 3) -> str:
    raw = normalize_text(html.unescape(str(term or ""))).lower()
    toks = TOKEN_RE.findall(raw)
    if not toks:
        return ""

    out: List[str] = []
    seen: set = set()
    for tok in toks:
        t = _strip_kw_particle(tok)
        if len(t) < 2:
            continue
        if t.isdigit():
            continue
        if DATE_LIKE_TOKEN_RE.match(t):
            continue
        if t in KEYWORD_EXTRACT_STOPWORDS:
            continue
        # Drop short verb-like forms that leak from sentence tails.
        if len(t) <= 6 and t.endswith(KEYWORD_VERBISH_ENDINGS):
            continue
        # Drop short verb-like tails that frequently pollute issue tags.
        if len(t) <= 4 and t.endswith(("했다", "한다", "됐다", "되는")):
            continue
        if t in seen:
            continue
        seen.add(t)
        out.append(t)
        if len(out) >= int(max_tokens):
            break

    if not out:
        return ""
    return " ".join(out)

def clean_review_keywords(
    keywords: List[str],
    representative_title: str,
    summary_lines: List[str],
    max_k: int = 6,
    min_k: int = REVIEW_KEYWORD_MIN_K
) -> List[str]:
    max_k = max(1, int(max_k))
    min_k = max(1, min(int(min_k), int(max_k)))
    focus_tokens = {t for t in title_tokens(representative_title) if not is_noise_keyword(t)}
    for ln in (summary_lines or []):
        for tok in TOKEN_RE.findall(str(ln).lower()):
            if not is_noise_keyword(tok):
                focus_tokens.add(tok)

    picked: List[str] = []
    seen: set = set()

    def _is_bad_tokens(toks: List[str]) -> bool:
        for t in toks:
            if t in REVIEW_KEYWORD_BLOCKLIST:
                return True
            if len(t) <= 5 and t.endswith(REVIEW_KEYWORD_BAD_SUFFIXES):
                return True
        return False

    def _try_add(raw_term: str, require_focus_for_single: bool = True) -> None:
        nk = normalize_keyword_candidate(str(raw_term), max_tokens=3)
        if not nk:
            return
        toks = [t for t in TOKEN_RE.findall(nk.lower()) if len(t) >= 2]
        if not toks:
            return
        if _is_bad_tokens(toks):
            return
        tok_set = set(toks)
        if require_focus_for_single and focus_tokens and len(tok_set) == 1 and not (tok_set & focus_tokens):
            return
        key = re.sub(r"\s+", "", nk.lower())
        if key in seen:
            return
        seen.add(key)
        picked.append(nk)

    # 1) strict pass
    for kw in (keywords or []):
        _try_add(kw, require_focus_for_single=True)
        if len(picked) >= int(max_k):
            return picked[: int(max_k)]

    # 2) relaxed pass when still short
    if len(picked) < int(min_k):
        for kw in (keywords or []):
            _try_add(kw, require_focus_for_single=False)
            if len(picked) >= int(min_k) or len(picked) >= int(max_k):
                break

    # 3) title/focus token backfill to satisfy minimum count with relevant tokens
    if len(picked) < int(min_k):
        for tok in title_tokens(representative_title):
            _try_add(tok, require_focus_for_single=False)
            if len(picked) >= int(min_k) or len(picked) >= int(max_k):
                break
    if len(picked) < int(min_k):
        for tok in sorted(focus_tokens):
            _try_add(tok, require_focus_for_single=False)
            if len(picked) >= int(min_k) or len(picked) >= int(max_k):
                break

    return picked[: int(max_k)]

def _extract_geo_tokens(text: str) -> set:
    toks = TOKEN_RE.findall((text or "").lower())
    out: set = set()
    for tok in toks:
        t = (tok or "").strip()
        if len(t) < 2:
            continue
        if t in GEO_CORE_TOKENS:
            out.add(t)
            continue
        if t.endswith(GEO_SUFFIXES):
            out.add(t)
    return out

def _is_local_incident_cluster(titles: List[str]) -> bool:
    tok_set: set = set()
    for t in titles:
        tok_set.update(title_tokens(t))
    return any(t in LOCAL_INCIDENT_TOKENS for t in tok_set)

def prune_geo_mismatch_members(
    members: List[int],
    titles: List[str],
    rep_idx: int,
    min_keep: int = 2
) -> Tuple[List[int], List[int]]:
    if len(members) < 3:
        return members, []

    cluster_titles = [str(titles[i]) for i in members]
    if not _is_local_incident_cluster(cluster_titles):
        return members, []

    geo_map: Dict[int, set] = {}
    freq: Dict[str, int] = {}
    for i in members:
        gs = _extract_geo_tokens(str(titles[i]))
        geo_map[i] = gs
        for g in gs:
            freq[g] = int(freq.get(g, 0) + 1)

    if not freq:
        return members, []

    anchor_min = max(2, int(math.ceil(len(members) * 0.35)))
    anchors = [g for g, c in sorted(freq.items(), key=lambda kv: (-kv[1], kv[0])) if c >= anchor_min]
    if not anchors:
        return members, []
    anchor_set = set(anchors[:2])

    rep_title = str(titles[rep_idx])
    kept: List[int] = []
    dropped: List[int] = []
    for i in members:
        gs = geo_map.get(i, set())
        if gs and (gs & anchor_set):
            kept.append(i)
            continue
        if title_jaccard(str(titles[i]), rep_title) >= 0.18:
            kept.append(i)
            continue
        dropped.append(i)

    if len(kept) < int(min_keep):
        return members, []
    return kept, dropped

def content_suspicious(title: str, content: str, cfg: PipelineConfig) -> bool:
    c = (content or "").strip()
    if len(c) < cfg.SUSP_MIN_CONTENT_CHARS:
        return True
    toks = title_tokens(title)
    if not toks:
        return False
    head = c[: cfg.SUSP_HEAD_MAX_CHARS].lower()
    hits = sum(1 for t in toks if t in head)
    need = cfg.SUSP_NEED_HITS_LONG if len(toks) >= 4 else cfg.SUSP_NEED_HITS_SHORT
    return hits < need

def drop_suspicious_rows(df: pd.DataFrame, cfg: PipelineConfig) -> Tuple[pd.DataFrame, int]:
    if df is None or len(df) == 0 or (not cfg.DROP_SUSPICIOUS_ROWS):
        return df, 0
    keep = []
    for t, c in zip(df["title"].astype(str), df["content"].astype(str)):
        keep.append(not content_suspicious(t, c, cfg))
    dropped = int((~pd.Series(keep)).sum())
    out = df.loc[keep].reset_index(drop=True)
    return out, dropped

