def collect_low_confidence_pairs(
    df: pd.DataFrame,
    emb: np.ndarray,
    texts_for_embed: List[str],
    bucket_key: str,
    max_pairs: int = 30
) -> List[Dict[str,Any]]:
    n = int(len(df))
    if n <= 1:
        return []
    topk = min(6, n - 1)
    if topk <= 0:
        return []

    idxs_all = np.arange(n, dtype=int)
    edges = knn_edges_cos(emb, idxs_all, topk=topk, th=0.76)
    seen: set = set()
    rows: List[Dict[str,Any]] = []
    for a, b in edges:
        i, j = (a, b) if a < b else (b, a)
        if i == j:
            continue
        key = (int(i), int(j))
        if key in seen:
            continue
        seen.add(key)

        cos = float(emb[i] @ emb[j])
        tj = title_jaccard(str(df.loc[i, "title"]), str(df.loc[j, "title"]))
        lt = text_token_jaccard(texts_for_embed[i], texts_for_embed[j], max_tok=140)
        # Keep near-miss pairs useful for QA triage.
        if cos < 0.80 and tj < 0.05 and lt < 0.06:
            continue
        score = (0.70 * cos) + (0.15 * tj) + (0.15 * lt)

        ra = df.loc[i]
        rb = df.loc[j]
        rows.append({
            "bucket": bucket_key,
            "rank": 0,
            "score": float(score),
            "cosine": float(cos),
            "title_jaccard": float(tj),
            "lead_jaccard": float(lt),
            "domain_a": str(ra.get("domain", "")),
            "title_a": str(ra.get("title", "")),
            "url_a": str(ra.get("url", "")),
            "domain_b": str(rb.get("domain", "")),
            "title_b": str(rb.get("title", "")),
            "url_b": str(rb.get("url", "")),
        })

    rows = sorted(rows, key=lambda x: (-float(x["score"]), -float(x["cosine"])))
    rows = rows[: max(1, int(max_pairs))]
    for k, r in enumerate(rows, start=1):
        r["rank"] = int(k)
    return rows

def build_review_issues_from_low_conf(
    df: pd.DataFrame,
    low_conf_rows: List[Dict[str,Any]],
    bucket_key: str,
    max_items: int = 3,
    min_score: float = 0.66,
    same_domain_strong_score: float = 0.74,
    generate_title: bool = True,
    title_max_chars: int = 64,
    force_source_title: bool = False
) -> List[Dict[str,Any]]:
    if df is None or len(df) == 0 or not low_conf_rows:
        return []

    url2idx: Dict[str, int] = {}
    c_url2idx: Dict[str, int] = {}
    for i, u in enumerate(df["url"].astype(str).tolist()):
        if u and u not in url2idx:
            url2idx[u] = int(i)
        cu = canonical_url(u)
        if cu and cu not in c_url2idx:
            c_url2idx[cu] = int(i)

    def find_idx(u: str) -> Optional[int]:
        if u in url2idx:
            return int(url2idx[u])
        cu = canonical_url(u)
        if cu in c_url2idx:
            return int(c_url2idx[cu])
        return None

    review_issues: List[Dict[str,Any]] = []
    used_article_idxs: set = set()
    for row in low_conf_rows:
        if len(review_issues) >= int(max_items):
            break
        score = float(row.get("score", 0.0))
        if score < float(min_score):
            continue

        ia = find_idx(str(row.get("url_a", "")))
        ib = find_idx(str(row.get("url_b", "")))
        if ia is None or ib is None or ia == ib:
            continue
        if int(ia) in used_article_idxs or int(ib) in used_article_idxs:
            continue

        ra = df.loc[int(ia)]
        rb = df.loc[int(ib)]
        ta = to_kst_iso(ra.get("_dt"))
        tb = to_kst_iso(rb.get("_dt"))
        t_sorted = sorted([x for x in [ta, tb] if x])

        title_a = str(ra.get("title", ""))
        title_b = str(rb.get("title", ""))
        source_rep_title_raw = title_a if len(title_a) >= len(title_b) else title_b
        source_rep_title = _clean_title_text(source_rep_title_raw) or source_rep_title_raw
        rep_url = str(ra.get("url", "")) if source_rep_title_raw == title_a else str(rb.get("url", ""))

        sample_texts = [
            f"{title_a} {str(ra.get('content', ''))}",
            f"{title_b} {str(rb.get('content', ''))}",
        ]
        kws_raw = extract_keywords(sample_texts, topk=6)
        sum_lines = extractive_news_style_summary(
            [str(ra.get("content", "")), str(rb.get("content", ""))],
            max_lines=5,
            min_lines=3
        )
        sum_lines = refine_summary_lines_by_focus(
            sum_lines,
            representative_title=source_rep_title,
            keywords=kws_raw,
            max_lines=5,
            min_lines=3
        )
        if not sum_lines:
            sum_lines = post_clean_summary_lines(
                [f"- {_clean_title_text(title_a) or title_a}", f"- {_clean_title_text(title_b) or title_b}"]
            )[:5]
        kws = clean_review_keywords(
            keywords=kws_raw,
            representative_title=source_rep_title,
            summary_lines=sum_lines,
            max_k=6,
            min_k=REVIEW_KEYWORD_MIN_K
        )
        rep_title = source_rep_title
        if bool(generate_title) and (not bool(force_source_title)):
            rep_title = compose_issue_title(
                source_title=source_rep_title,
                keywords=kws,
                summary_lines=sum_lines,
                max_chars=int(title_max_chars),
                candidate_titles=[title_a, title_b]
            )
        rep_title = _clean_title_text(rep_title) or source_rep_title

        arts = []
        for r in [ra, rb]:
            arts.append({
                "domain": str(r.get("domain", "")),
                "date": str(r.get("date", "")),
                "category": str(r.get("category", "")),
                "title": str(r.get("title", "")),
                "url": str(r.get("url", "")),
            })

        doms = set(x.get("domain", "") for x in arts if x.get("domain", ""))
        if len(doms) < 2 and score < float(same_domain_strong_score):
            continue

        ridx = len(review_issues) + 1
        review_issues.append({
            "issue_id": f"{bucket_key}__R{ridx:03d}",
            "bucket": bucket_key,
            "issue_type": "review_needed",
            "time_start": t_sorted[0] if t_sorted else "",
            "time_end": t_sorted[-1] if t_sorted else "",
            "representative_title": rep_title,
            "source_representative_title": source_rep_title,
            "representative_url": rep_url,
            "keywords": kws,
            "stats": {
                "size": 2,
                "domains": int(len(doms)),
                "low_conf_score": score,
                "cosine": float(row.get("cosine", 0.0)),
                "title_jaccard": float(row.get("title_jaccard", 0.0)),
                "lead_jaccard": float(row.get("lead_jaccard", 0.0)),
            },
            "summary_lines": sum_lines,
            "articles": arts,
        })
        used_article_idxs.add(int(ia))
        used_article_idxs.add(int(ib))
    return review_issues

