def canonical_url(url: str) -> str:
    try:
        from urllib.parse import urlparse, parse_qsl, urlencode, urlunparse
        if not url:
            return ""
        u = str(url).strip()
        if not u:
            return ""
        if "://" not in u:
            u = "https://" + u
        p = urlparse(u)
        host = (p.netloc or "").lower()
        if host.startswith("www."):
            host = host[4:]
        path = p.path or ""
        if path != "/" and path.endswith("/"):
            path = path[:-1]

        tracking_keys = {"fbclid","gclid","yclid","igshid","mc_cid","mc_eid","_gl","spm","ref","referrer","source","src","feature"}
        q = []
        for k, v in parse_qsl(p.query, keep_blank_values=True):
            lk = (k or "").lower()
            if lk.startswith("utm_"):
                continue
            if lk in tracking_keys:
                continue
            q.append((k, v))
        q.sort(key=lambda kv: (kv[0], kv[1]))
        query = urlencode(q, doseq=True)

        new_p = (p.scheme.lower() if p.scheme else "https", host, path, "", query, "")
        return urlunparse(new_p)
    except Exception:
        return (str(url).strip() if url else "")

def row_dedup_key(url: str, title: str, content: str) -> str:
    cu = canonical_url(url)
