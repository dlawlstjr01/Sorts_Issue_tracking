SENT_SPLIT_RE = re.compile(r"(?<=[.!?。])\s+|\n+")
DA_SENT_BOUNDARY_RE = re.compile(r"(다\.)\s+")

def split_sentences_ko(text: str) -> List[str]:
    if not isinstance(text, str):
        return []
    t = DA_SENT_BOUNDARY_RE.sub(r"\1\n", text)
    sents = [s.strip() for s in SENT_SPLIT_RE.split(t) if s.strip()]
    sents = [s for s in sents if len(s) >= 10]
    return sents

def post_clean_summary_lines(lines: List[str]) -> List[str]:
    out, seen = [], set()
    seen_tok_sets: List[set] = []
    seen_norm: List[str] = []
    for ln in lines:
        s = (ln or "").strip()
        s = EMAIL_RE.sub(" ", s)
        s = URL_RE.sub(" ", s)
        s = BOILERPLATE_RE.sub(" ", s)
        s = WS_RE.sub(" ", s).strip()
        if not s:
            continue
        if "등록번호" in s and "사업자" in s:
            continue
        if len(s) < 8:
            continue
        if "관련 기사" in s:
            continue
        if "재판매 및 db금지" in s.lower():
            continue
        if s.count(" - ") >= 3:
            continue
        if len(re.findall(r"\d{4}\.\d{2}\.\d{2}", s)) >= 2:
            continue
        key = sha1(s.lower())
        if key in seen:
            continue
        toks = {t for t in TOKEN_RE.findall(s.lower()) if len(t) >= 2 and (not t.isdigit())}
        if toks:
            dup = False
            for prev in seen_tok_sets:
                j = len(toks & prev) / max(1, len(toks | prev))
                if j >= float(SUMMARY_NEAR_DUP_JACC):
                    dup = True
                    break
            if dup:
                continue
        norm = re.sub(r"[^A-Za-z0-9가-힣]+", "", s.lower())
        if len(norm) >= int(SUMMARY_MIN_NORM_LEN):
            near = False
            for p in seen_norm:
                if norm in p or p in norm:
                    near = True
                    break
            if near:
                continue
            seen_norm.append(norm)
        seen.add(key)
        if toks:
            seen_tok_sets.append(toks)
        out.append(s if s.startswith("-") else ("- " + s))
    return out

def extract_keywords(texts: List[str], topk: int = 10) -> List[str]:
    docs = [normalize_text(t) for t in texts if isinstance(t, str) and t.strip()]
    if not docs:
        return []
    if TfidfVectorizer is None:
        from collections import Counter
        tok = []
        for d in docs:
            tok += [normalize_keyword_candidate(w, max_tokens=1) for w in TOKEN_RE.findall(d.lower())]
        tok = [w for w in tok if w]
        return [w for w, _ in Counter(tok).most_common(topk)]
    try:
        vec = TfidfVectorizer(min_df=1, max_df=0.95, ngram_range=(1,2))
        X = vec.fit_transform(docs)
        scores = np.asarray(X.mean(axis=0)).ravel()
        terms = np.array(vec.get_feature_names_out())
        order = np.argsort(-scores)
        # Aggregate TF-IDF scores after keyword normalization.
        agg: Dict[str, float] = {}
        for i in order[: topk * 20]:
            t = normalize_keyword_candidate(str(terms[i]), max_tokens=3)
            if not t:
                continue
            agg[t] = float(agg.get(t, 0.0) + float(scores[i]))

        ranked = sorted(agg.items(), key=lambda kv: -float(kv[1]))
        picked: List[str] = []
        seen_keys: List[str] = []
        for kw, _sc in ranked:
            k = re.sub(r"\s+", "", kw.lower())
            skip = False
            for sk in seen_keys:
                # Remove exact/very-near duplicates from particle/spacing variants.
                if k == sk:
                    skip = True
                    break
                if len(k) <= 3 and (k in sk):
                    skip = True
                    break
                if len(sk) <= 3 and (sk in k):
                    skip = True
                    break
            if skip:
                continue
            picked.append(kw)
            seen_keys.append(k)
            if len(picked) >= int(topk):
                break
        return picked[:topk]
    except Exception:
        return []

def extractive_news_style_summary(texts: List[str], max_lines: int = 7, min_lines: int = 5) -> List[str]:
    joined = "\n".join([normalize_text(t) for t in texts if isinstance(t, str) and t.strip()])
    sents = split_sentences_ko(joined)
    if not sents:
        return []
    scores = None
    if TfidfVectorizer is not None:
        try:
            vec = TfidfVectorizer(min_df=1, max_df=0.95, ngram_range=(1,2))
            X = vec.fit_transform(sents)
            scores = np.asarray(X.sum(axis=1)).ravel().astype(np.float32)
        except Exception:
            scores = None
    if scores is None:
        scores = np.array([min(200, len(s)) for s in sents], dtype=np.float32)

    k = min(max_lines, len(sents))
    top_idx = np.argsort(-scores)[:k]
    top_idx = sorted(top_idx.tolist())
    lines = ["- " + sents[i] for i in top_idx]
    lines = post_clean_summary_lines(lines)
    if len(lines) < min_lines:
        lines = post_clean_summary_lines(["- " + s for s in sents[:max_lines]])
    return lines[:max_lines]

def refine_summary_lines_by_focus(
    lines: List[str],
    representative_title: str,
    keywords: List[str],
    max_lines: int = 7,
    min_lines: int = 4
) -> List[str]:
    if not lines:
        return []
    norm_lines = [ln if str(ln).strip().startswith("-") else ("- " + str(ln).strip()) for ln in lines if str(ln).strip()]
    if not norm_lines:
        return []

    title_set = {t for t in title_tokens(representative_title) if not is_noise_keyword(t)}
    kw_set: set = set()
    for kw in (keywords or []):
        for tok in TOKEN_RE.findall(str(kw).lower()):
            if not is_noise_keyword(tok):
                kw_set.add(tok)
    focus_set = title_set | kw_set
    if not focus_set:
        return post_clean_summary_lines(norm_lines)[:max_lines]

    scored: List[Tuple[int, str, float]] = []
    for idx, ln in enumerate(norm_lines):
        txt = str(ln).lstrip("- ").strip()
        toks = [t for t in TOKEN_RE.findall(txt.lower()) if not is_noise_keyword(t)]
        if not toks:
            continue
        tok_set = set(toks)
        shared_title = len(tok_set & title_set)
        shared_focus = len(tok_set & focus_set)
        score = float((2.0 * shared_title) + shared_focus)
        scored.append((idx, ln, score))
    if not scored:
        return post_clean_summary_lines(norm_lines)[:max_lines]

    strong = [x for x in scored if x[2] > 0.0]
    if len(strong) >= int(min_lines):
        picked = sorted(strong, key=lambda x: (-x[2], x[0]))[: int(max_lines)]
    else:
        need = min(int(max_lines), max(int(min_lines), len(scored)))
        picked = sorted(scored, key=lambda x: (-x[2], x[0]))[:need]
    picked = sorted(picked, key=lambda x: x[0])
    out = post_clean_summary_lines([x[1] for x in picked])
    if len(out) < int(min_lines):
        out = post_clean_summary_lines(norm_lines[: int(max_lines)])
    return out[: int(max_lines)]

def _truncate_with_ellipsis(s: str, max_chars: int) -> str:
    if max_chars <= 0:
        return ""
    if len(s) <= max_chars:
        return s
    if max_chars <= 3:
        return s[:max_chars]
    return s[: max_chars - 3].rstrip() + "..."

def _clean_title_text(s: str) -> str:
    t = html.unescape(str(s or ""))
    t = normalize_text(t)
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"\s*[-|]\s*(뉴스웨이|연합뉴스|뉴시스|데일리안|머니투데이)\s*$", "", t, flags=re.IGNORECASE)
    # Drop trailing campaign/series tag blocks like: [관세 리셋 쇼크]
    t = re.sub(r"\s*\[[^\]]{1,24}\]\s*$", "", t)
    # Drop dangling unmatched bracket tail like: [...[관세 리셋 쇼크
    t = re.sub(r"\s*\[[^\]]{1,24}\s*$", "", t)
    # Drop trailing parenthetical tags like "(종합)" and dangling "(종합".
    t = re.sub(r"\s*\((?:종합|속보|단독|포토|사진|영상|1보|2보|3보)\)\s*$", "", t, flags=re.IGNORECASE)
    t = re.sub(r"\s*\((?:종합|속보|단독|포토|사진|영상|1보|2보|3보)\s*$", "", t, flags=re.IGNORECASE)
    t = t.strip(" -|:;[]()")
    return t

def _title_token_set(title: str) -> set:
    raw = str(title or "")
    out = {tok for tok in TOKEN_RE.findall(raw.lower()) if not is_noise_keyword(tok)}
    for ch, mapped in HANJA_TITLE_MAP.items():
        if ch in raw:
            for tok in TOKEN_RE.findall(mapped.lower()):
                if not is_noise_keyword(tok):
                    out.add(tok)
    return out

def _best_consensus_title(candidate_titles: List[str], keywords: List[str]) -> str:
    cleaned: List[str] = []
    seen: set = set()
    for raw in (candidate_titles or []):
        t = _clean_title_text(raw)
        if len(t) < 6:
            continue
        k = t.lower()
        if k in seen:
            continue
        seen.add(k)
        cleaned.append(t)
    if not cleaned:
        return ""

    kw_set: set = set()
    for kw in (keywords or []):
        for tok in TOKEN_RE.findall(str(kw).lower()):
            if not is_noise_keyword(tok):
                kw_set.add(tok)

    token_sets: List[set] = []
    token_freq: Dict[str, int] = {}
    for t in cleaned:
        toks = _title_token_set(t)
        token_sets.append(toks)
        for tok in toks:
            token_freq[tok] = int(token_freq.get(tok, 0)) + 1

    best_i = 0
    best_score = -1e9
    for i, t in enumerate(cleaned):
        toks = token_sets[i]
        kw_hit = len(toks & kw_set)
        consensus = sum(token_freq.get(tok, 0) for tok in toks)
        length_penalty = abs(len(t) - 34) / 34.0
        score = (3.0 * kw_hit) + (1.0 * consensus) - (0.8 * length_penalty)
        # source_title is appended first in compose_issue_title(); keep a mild stability bias
        if i == 0:
            score += 0.4
        if len(t) > 72:
            score -= 1.5
        if "[" in t or "]" in t:
            score -= 1.0
        if score > best_score or (abs(score - best_score) < 1e-9 and len(t) < len(cleaned[best_i])):
            best_score = score
            best_i = i
    return cleaned[best_i]

def compose_issue_title(
    source_title: str,
    keywords: List[str],
    summary_lines: List[str],
    max_chars: int = 64,
    candidate_titles: Optional[List[str]] = None
) -> str:
    candidates: List[str] = []
    if source_title:
        candidates.append(str(source_title))
    for t in (candidate_titles or []):
        candidates.append(str(t))
    base = _best_consensus_title(candidates, keywords)
    if not base:
        base = _clean_title_text(source_title)

    if not base:
        for ln in (summary_lines or []):
            txt = str(ln).lstrip("- ").strip()
            txt = normalize_text(txt)
            txt = re.split(r"[.?!]\s+|;\s+|:\s+", txt, maxsplit=1)[0].strip()
            txt = re.sub(r"\s+", " ", txt).strip(" -:")
            if len(txt) >= 8:
                base = txt
                break

    if not base:
        kw_parts: List[str] = []
        seen_kw: set = set()
        for kw in (keywords or []):
            k = normalize_text(str(kw))
            k = re.sub(r"\s+", " ", k).strip(" -:")
            if not k:
                continue
            lk = k.lower()
            if lk in seen_kw:
                continue
            seen_kw.add(lk)
            kw_parts.append(k)
            if len(kw_parts) >= 2:
                break
        base = (("·".join(kw_parts) + " 이슈") if kw_parts else "주요 이슈 업데이트")
    return _truncate_with_ellipsis(base, int(max_chars))

def to_kst_iso(ts_like: Any) -> str:
    ts = pd.to_datetime(ts_like, errors="coerce")
    if pd.isna(ts):
        return ""
    try:
        if getattr(ts, "tzinfo", None) is None:
            ts = ts.tz_localize(KST)
        else:
            ts = ts.tz_convert(KST)
        return ts.isoformat(timespec="seconds")
    except Exception:
        try:
            ts2 = pd.to_datetime(ts_like, errors="coerce", utc=True)
            if pd.isna(ts2):
                return ""
            return ts2.tz_convert(KST).isoformat(timespec="seconds")
        except Exception:
            return ""

