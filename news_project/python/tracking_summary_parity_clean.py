SENT_SPLIT_RE = re.compile(r"(?<=[.!?。])\s+|\n+")
DA_SENT_BOUNDARY_RE = re.compile(r"(다\.)\s+")

def split_sentences_ko(text: str) -> List[str]:
    if not isinstance(text, str):
        return []
    t = DA_SENT_BOUNDARY_RE.sub(r"\1\n", text)
    sents = [s.strip() for s in SENT_SPLIT_RE.split(t) if s.strip()]
    sents = [s for s in sents if len(s) >= 10]
    return sents

def post_clean_summary_lines(lines: List[str]) -> List[str]:
    out, seen = [], set()
    seen_tok_sets: List[set] = []
    seen_norm: List[str] = []
    for ln in lines:
        s = (ln or "").strip()
        s = EMAIL_RE.sub(" ", s)
        s = URL_RE.sub(" ", s)
        s = BOILERPLATE_RE.sub(" ", s)
        s = WS_RE.sub(" ", s).strip()
        if not s:
            continue
        if "등록번호" in s and "사업자" in s:
            continue
        if len(s) < 8:
            continue
        if "관련 기사" in s:
            continue
        if "재판매 및 db금지" in s.lower():
            continue
        if s.count(" - ") >= 3:
            continue
        if len(re.findall(r"\d{4}\.\d{2}\.\d{2}", s)) >= 2:
            continue
        if len(SUMMARY_REPEAT_NOISE_RE.findall(s)) >= 3:
            continue
        if not _summary_line_usable(s):
            continue
        key = sha1(s.lower())
        if key in seen:
            continue
        toks = {t for t in TOKEN_RE.findall(s.lower()) if len(t) >= 2 and (not t.isdigit())}
        if toks:
            dup = False
            for prev in seen_tok_sets:
                j = len(toks & prev) / max(1, len(toks | prev))
                if j >= float(SUMMARY_NEAR_DUP_JACC):
                    dup = True
                    break
            if dup:
                continue
        norm = re.sub(r"[^A-Za-z0-9가-힣]+", "", s.lower())
        if len(norm) >= int(SUMMARY_MIN_NORM_LEN):
            near = False
            for p in seen_norm:
                if norm in p or p in norm:
                    near = True
                    break
            if near:
                continue
            seen_norm.append(norm)
        seen.add(key)
        if toks:
            seen_tok_sets.append(toks)
        out.append(s if s.startswith("-") else ("- " + s))
    return out

def extract_keywords(texts: List[str], topk: int = 10) -> List[str]:
    docs = [normalize_text(t) for t in texts if isinstance(t, str) and t.strip()]
    if not docs:
        return []
    if TfidfVectorizer is None:
        from collections import Counter
        tok = []
        for d in docs:
            tok += [normalize_keyword_candidate(w, max_tokens=1) for w in TOKEN_RE.findall(d.lower())]
        tok = [w for w in tok if w]
        return [w for w, _ in Counter(tok).most_common(topk)]
    try:
        vec = TfidfVectorizer(min_df=1, max_df=0.95, ngram_range=(1,2))
        X = vec.fit_transform(docs)
        scores = np.asarray(X.mean(axis=0)).ravel()
        terms = np.array(vec.get_feature_names_out())
        order = np.argsort(-scores)
        # Aggregate TF-IDF scores after keyword normalization.
        agg: Dict[str, float] = {}
        for i in order[: topk * 20]:
            t = normalize_keyword_candidate(str(terms[i]), max_tokens=3)
            if not t:
                continue
            agg[t] = float(agg.get(t, 0.0) + float(scores[i]))

        ranked = sorted(agg.items(), key=lambda kv: -float(kv[1]))
        picked: List[str] = []
        seen_keys: List[str] = []
        for kw, _sc in ranked:
            k = re.sub(r"\s+", "", kw.lower())
            skip = False
            for sk in seen_keys:
                # Remove exact/very-near duplicates from particle/spacing variants.
                if k == sk:
                    skip = True
                    break
                if len(k) <= 3 and (k in sk):
                    skip = True
                    break
                if len(sk) <= 3 and (sk in k):
                    skip = True
                    break
            if skip:
                continue
            picked.append(kw)
            seen_keys.append(k)
            if len(picked) >= int(topk):
                break
        return picked[:topk]
    except Exception:
        return []

def extractive_news_style_summary(texts: List[str], max_lines: int = 7, min_lines: int = 5) -> List[str]:
    joined = "\n".join([normalize_text(t) for t in texts if isinstance(t, str) and t.strip()])
    sents = split_sentences_ko(joined)
    if not sents:
        return []
    scores = None
    if TfidfVectorizer is not None:
        try:
            vec = TfidfVectorizer(min_df=1, max_df=0.95, ngram_range=(1,2))
            X = vec.fit_transform(sents)
            scores = np.asarray(X.sum(axis=1)).ravel().astype(np.float32)
        except Exception:
            scores = None
    if scores is None:
        scores = np.array([min(200, len(s)) for s in sents], dtype=np.float32)

    k = min(max_lines, len(sents))
    top_idx = np.argsort(-scores)[:k]
    top_idx = sorted(top_idx.tolist())
    lines = ["- " + sents[i] for i in top_idx]
    lines = post_clean_summary_lines(lines)
    if len(lines) < min_lines:
        lines = post_clean_summary_lines(["- " + s for s in sents[:max_lines]])
    return lines[:max_lines]

def refine_summary_lines_by_focus(
    lines: List[str],
    representative_title: str,
    keywords: List[str],
    max_lines: int = 7,
    min_lines: int = 4
) -> List[str]:
    if not lines:
        return []
    norm_lines = [ln if str(ln).strip().startswith("-") else ("- " + str(ln).strip()) for ln in lines if str(ln).strip()]
    if not norm_lines:
        return []

    title_set = {t for t in title_tokens(representative_title) if not is_noise_keyword(t)}
    kw_set: set = set()
    for kw in (keywords or []):
        for tok in TOKEN_RE.findall(str(kw).lower()):
            if not is_noise_keyword(tok):
                kw_set.add(tok)
    focus_set = title_set | kw_set
    if not focus_set:
        return post_clean_summary_lines(norm_lines)[:max_lines]

    scored: List[Tuple[int, str, float]] = []
    for idx, ln in enumerate(norm_lines):
        txt = str(ln).lstrip("- ").strip()
        if not _summary_line_usable(txt):
            continue
        info_tokens = set(_summary_content_tokens(txt))
        if not info_tokens:
            continue
        shared_title = len(info_tokens & title_set)
        shared_focus = len(info_tokens & focus_set)
        length_bonus = min(len(txt), int(SUMMARY_COMPLETE_SOFT_MAX_CHARS)) / 80.0
        info_bonus = min(len(info_tokens), 6) * 0.25
        score = float((2.0 * shared_title) + shared_focus + length_bonus + info_bonus)
        scored.append((idx, ln, score))
    if not scored:
        return post_clean_summary_lines(norm_lines)[:max_lines]

    strong = [x for x in scored if x[2] > 0.0]
    if strong:
        picked = sorted(strong, key=lambda x: (-x[2], x[0]))[: int(max_lines)]
    else:
        return []
    picked = sorted(picked, key=lambda x: x[0])
    out = post_clean_summary_lines([x[1] for x in picked])
    return out[: int(max_lines)]

def _truncate_with_ellipsis(s: str, max_chars: int) -> str:
    if max_chars <= 0:
        return ""
    if len(s) <= max_chars:
        return s
    if max_chars <= 3:
        return s[:max_chars]
    return s[: max_chars - 3].rstrip() + "..."

def _clean_title_text(s: str) -> str:
    t = html.unescape(str(s or ""))
    t = normalize_text(t)
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"\s*[-|]\s*(뉴스웨이|연합뉴스|뉴시스|데일리안|머니투데이)\s*$", "", t, flags=re.IGNORECASE)
    # Drop trailing campaign/series tag blocks like: [관세 리셋 쇼크]
    t = re.sub(r"\s*\[[^\]]{1,24}\]\s*$", "", t)
    # Drop dangling unmatched bracket tail like: [...[관세 리셋 쇼크
    t = re.sub(r"\s*\[[^\]]{1,24}\s*$", "", t)
    # Drop trailing parenthetical tags like "(종합)" and dangling "(종합".
    t = re.sub(r"\s*\((?:종합|속보|단독|포토|사진|영상|1보|2보|3보)\)\s*$", "", t, flags=re.IGNORECASE)
    t = re.sub(r"\s*\((?:종합|속보|단독|포토|사진|영상|1보|2보|3보)\s*$", "", t, flags=re.IGNORECASE)
    t = t.strip(" -|:;[]()")
    return t

def _title_token_set(title: str) -> set:
    raw = str(title or "")
    out = {tok for tok in TOKEN_RE.findall(raw.lower()) if not is_noise_keyword(tok)}
    for ch, mapped in HANJA_TITLE_MAP.items():
        if ch in raw:
            for tok in TOKEN_RE.findall(mapped.lower()):
                if not is_noise_keyword(tok):
                    out.add(tok)
    return out

def _is_geo_like_match_token(tok: str) -> bool:
    t = (tok or "").strip().lower()
    if not t:
        return False
    if t in GEO_CORE_TOKENS:
        return True
    return len(t) >= 2 and t.endswith(GEO_SUFFIXES)

def _title_match_token_set(title: str) -> set:
    out = set()
    geo_tokens = set()
    for tok in _title_token_set(title):
        if tok in DISPLAY_MATCH_STOPWORDS:
            continue
        if _is_geo_like_match_token(tok):
            geo_tokens.add(tok)
            continue
        out.add(tok)
    return out or geo_tokens

def _compact_title_summary(title: str, max_chars: int = SUMMARY_SHORT_MAX_CHARS) -> str:
    t = _clean_title_text(title)
    t = re.sub(r"^(?:속보|단독)\s+", "", t).strip()
    parts = [
        p.strip(" -:;,/[]()")
        for p in re.split(r"\s*(?:\.\.\.|…|:| - )\s*", t)
        if p and p.strip(" -:;,/[]()")
    ]
    if len(parts) >= 2 and len(parts[0]) <= max(12, int(max_chars * 0.7)):
        t = f"{parts[0]}, {parts[1]}"
    elif parts:
        t = parts[0]
    t = re.sub(r"\s+", " ", t).strip(" -:;,/")
    if _is_source_only_summary_line(t):
        return ""
    return _truncate_with_ellipsis(t, int(max_chars))

def _title_to_complete_sentence(title: str) -> str:
    t = _clean_title_text(title)
    t = re.sub(r"\s*(?:\.\.\.|…)\s*", ", ", t).strip()
    t = re.sub(r"\s+", " ", t).strip(" -:;,/")
    if not t:
        return ""
    if _is_source_only_summary_line(t):
        return ""
    if "간추린 뉴스" in t or t.endswith(" 外") or t.endswith(" 외"):
        return ""
    if _looks_complete_sentence(t):
        finalized = _finalize_complete_sentence(t)
        return finalized if _summary_line_usable(finalized) else ""

    if re.search(r"(?:처음|최초|최대|최저)$", t):
        candidate = t + "이다."
        return candidate if _summary_line_usable(candidate) else ""
    if re.search(r"(?:가능성|우려|논란|관측|전망)$", t):
        candidate = t + "이 제기됐다."
        return candidate if _summary_line_usable(candidate) else ""
    if re.search(
        r"(?:축소|확대|폐지|개편|강화|완화|공개|발표|추진|중단|재개|검토|지원|출시|출범|"
        r"선출|확정|돌파|급등|급락|급증|급감|상승|하락|증가|감소|구속|체포|기소|사퇴|"
        r"복귀|방문|회동|합의|거부|승인|통과|부결|제안|발사|요격|배치|도입|철수|해체)$",
        t,
    ):
        candidate = t + "됐다."
        return candidate if _summary_line_usable(candidate) else ""
    candidate = t + "."
    return candidate if _summary_line_usable(candidate) else ""

def _title_urgency_score(title: str, is_representative: bool = False) -> int:
    raw = html.unescape(str(title or ""))
    if not raw.strip():
        return 0

    score = 0
    if URGENT_TITLE_PREFIX_RE.search(raw):
        score += 6

    cleaned = _clean_title_text(raw)
    if not cleaned:
        return score

    marker_hits = {marker for marker in URGENT_TITLE_MARKERS if marker in cleaned}
    score += len(marker_hits) * 2

    if is_representative and score > 0:
        score += 1

    return score

def build_priority_title_summary_lines(
    representative_title: str,
    articles: List[Dict[str, Any]],
    max_lines: int = URGENT_TITLE_MAX_LINES,
) -> List[str]:
    if int(max_lines) <= 0:
        return []

    candidates: List[Tuple[int, int, str]] = []
    seen_keys: set = set()
    raw_candidates: List[Dict[str, Any]] = [{"title": representative_title, "is_representative": True}]
    raw_candidates.extend(list(articles or []))

    for idx, article in enumerate(raw_candidates):
        title = str(article.get("title", "") or "").strip()
        if not title:
            continue

        score = _title_urgency_score(
            title,
            is_representative=bool(article.get("is_representative")) or idx == 0,
        )
        if score <= 0:
            continue

        line = _title_to_complete_sentence(title)
        if not line:
            continue

        key = _summary_line_key(line)
        if not key or key in seen_keys:
            continue

        seen_keys.add(key)
        candidates.append((score, idx, line))

    candidates.sort(key=lambda x: (-x[0], x[1]))
    return [line for _score, _idx, line in candidates[: int(max_lines)]]

def _normalize_complete_summary_output(lines_or_text: Any, max_lines: int) -> List[str]:
    raw_items: List[str] = []
    if isinstance(lines_or_text, (list, tuple)):
        raw_items = [str(x) for x in lines_or_text if str(x or "").strip()]
    else:
        raw = str(lines_or_text or "").strip()
        if raw:
            raw_items = [raw]

    picked: List[str] = []
    seen: List[str] = []
    for raw in raw_items:
        text = clean_summary_text(raw)
        for block in re.split(r"\n+", text):
            s = str(block or "").lstrip("- ").strip()
            if not s:
                continue
            if "..." in s or "…" in s:
                continue
            finalized = _finalize_complete_sentence(s)
            if not finalized:
                continue
            if not _summary_line_usable(finalized):
                continue
            key = _summary_line_key(finalized)
            if not key or key in seen:
                continue
            seen.append(key)
            picked.append("- " + finalized)
            if len(picked) >= int(max_lines):
                return picked[: int(max_lines)]
    return picked[: int(max_lines)]

def build_headline_summary_lines(
    representative_title: str,
    articles: List[Dict[str, Any]],
    max_lines: int = SUMMARY_SHORT_MAX_LINES,
    max_chars: int = SUMMARY_SHORT_MAX_CHARS,
) -> List[str]:
    candidates: List[str] = []
    if representative_title:
        candidates.append(representative_title)
    for article in (articles or []):
        title = str(article.get("title", "") or "").strip()
        if title:
            candidates.append(title)

    out: List[str] = []
    seen_keys: List[str] = []
    rep_title = _clean_title_text(representative_title)
    rep_tokens = _title_match_token_set(rep_title)

    for raw in candidates:
        line = _compact_title_summary(raw, max_chars=max_chars)
        if not line:
            continue
        key = _summary_line_key(line)
        if not key:
            continue
        duplicate = False
        for prev in seen_keys:
            if key == prev or key in prev or prev in key:
                duplicate = True
                break
        if duplicate:
            continue

        if out and rep_tokens:
            toks = _title_match_token_set(line)
            if toks and not (toks & rep_tokens) and title_jaccard(rep_title, line) < 0.08:
                continue

        out.append("- " + line)
        seen_keys.append(key)
        if len(out) >= int(max_lines):
            break

    return out[: int(max_lines)]

def _issue_article_focus_score(
    representative_title: str,
    representative_content: str,
    article_title: str,
    article_content: str,
) -> float:
    rep_title = _clean_title_text(representative_title) or clean_html_text(representative_title)
    art_title = _clean_title_text(article_title) or clean_html_text(article_title)
    rep_content = sanitize_summary_source_text(representative_content, title=rep_title)
    art_content = sanitize_summary_source_text(article_content, title=art_title)

    rep_focus = _title_match_token_set(rep_title)
    art_focus = _title_match_token_set(art_title)
    shared_focus = len(rep_focus & art_focus)
    title_sim = title_jaccard(rep_title, art_title)
    text_sim = text_token_jaccard(
        f"{rep_title} {rep_content[:800]}",
        f"{art_title} {art_content[:800]}",
        max_tok=120,
    )
    return float((title_sim * 4.0) + (text_sim * 2.5) + (min(shared_focus, 4) * 0.6))

def pick_issue_articles_for_summary(
    representative_title: str,
    representative_content: str,
    articles: List[Dict[str, Any]],
    max_articles: int = 5,
) -> List[Dict[str, Any]]:
    if not articles:
        return []

    scored: List[Tuple[float, int, Dict[str, Any]]] = []
    for idx, article in enumerate(articles):
        title = str(article.get("title", "") or "")
        content = str(article.get("content", "") or "")
        score = _issue_article_focus_score(
            representative_title=representative_title,
            representative_content=representative_content,
            article_title=title,
            article_content=content,
        )
        if bool(article.get("is_representative")):
            score += 0.35
        scored.append((float(score), int(idx), article))

    scored.sort(key=lambda x: (-x[0], x[1]))

    picked: List[Dict[str, Any]] = []
    representative_picked = False
    for score, _idx, article in scored:
        if bool(article.get("is_representative")) and not representative_picked:
            picked.append(article)
            representative_picked = True
            break

    if not representative_picked:
        picked.append(scored[0][2])

    for score, _idx, article in scored:
        if article in picked:
            continue
        title = str(article.get("title", "") or "")
        content = str(article.get("content", "") or "")
        keep = (
            score >= 0.55
            or title_jaccard(representative_title, title) >= 0.10
            or text_token_jaccard(
                f"{representative_title} {sanitize_summary_source_text(representative_content, representative_title)[:800]}",
                f"{title} {sanitize_summary_source_text(content, title)[:800]}",
                max_tok=120,
            ) >= 0.10
        )
        if not keep:
            continue
        picked.append(article)
        if len(picked) >= int(max_articles):
            break

    if len(picked) < min(2, len(articles)):
        for _score, _idx, article in scored:
            if article in picked:
                continue
            picked.append(article)
            if len(picked) >= min(int(max_articles), len(articles)):
                break

    return picked[: int(max_articles)]

def filter_issue_articles_for_display(
    representative_title: str,
    representative_content: str,
    representative_category: str,
    articles: List[Dict[str, Any]],
    min_articles: int = 2,
    max_articles: int = 10,
) -> List[Dict[str, Any]]:
    if not articles:
        return []

    rep_title = _clean_title_text(representative_title) or clean_html_text(representative_title)
    rep_content = sanitize_summary_source_text(representative_content, title=rep_title)
    rep_bcat = broad_category(representative_category)
    rep_tokens = _title_match_token_set(rep_title)

    kept: List[Dict[str, Any]] = []
    representative_added = False

    for article in articles:
        title = _clean_title_text(article.get("title", "") or "") or clean_html_text(article.get("title", "") or "")
        content = sanitize_summary_source_text(article.get("content", "") or "", title=title)
        cat = str(article.get("category", "") or "")
        bcat = broad_category(cat)
        is_representative = bool(article.get("is_representative"))

        title_sim = title_jaccard(rep_title, title)
        text_sim = text_token_jaccard(
            f"{rep_title} {rep_content[:800]}",
            f"{title} {content[:800]}",
            max_tok=120,
        )
        article_tokens = _title_match_token_set(title)
        focus_overlap = len(rep_tokens & article_tokens)
        score = _issue_article_focus_score(
            representative_title=rep_title,
            representative_content=rep_content,
            article_title=title,
            article_content=content,
        )

        if rep_bcat != "unknown" and bcat != "unknown" and rep_bcat != bcat:
            score -= 0.35

        keep = is_representative
        if not keep:
            keep = (
                score >= 1.05
                or (title_sim >= 0.14 and text_sim >= 0.10)
                or (focus_overlap >= 2 and text_sim >= 0.08)
            )
            if rep_tokens and article_tokens and focus_overlap == 0:
                keep = keep and text_sim >= 0.18 and title_sim >= 0.12
            if rep_bcat != "unknown" and bcat != "unknown" and rep_bcat != bcat:
                keep = keep and score >= 1.35

        if not keep:
            continue

        next_article = dict(article)
        next_article["title"] = title
        next_article["content"] = content
        kept.append(next_article)
        representative_added = representative_added or is_representative

        if len(kept) >= int(max_articles):
            break

    if not representative_added and articles:
        first = dict(articles[0])
        first["title"] = _clean_title_text(first.get("title", "") or "") or clean_html_text(first.get("title", "") or "")
        first["content"] = sanitize_summary_source_text(first.get("content", "") or "", title=first["title"])
        kept = [first] + [x for x in kept if str(x.get("article_id") or x.get("id") or "") != str(first.get("article_id") or first.get("id") or "")]

    if len(kept) < int(min_articles):
        return []

    return kept[: int(max_articles)]

def build_issue_short_summary(
    representative_title: str,
    representative_content: str,
    articles: List[Dict[str, Any]],
    stored_short_summary: str = "",
    max_lines: int = SUMMARY_SHORT_TARGET_LINES,
) -> str:
    requested_lines = int(max_lines or SUMMARY_SHORT_TARGET_LINES)
    target_lines = max(requested_lines, int(SUMMARY_SHORT_MIN_LINES))
    target_lines = min(target_lines, int(SUMMARY_SHORT_MAX_LINES))
    picked_articles = pick_issue_articles_for_summary(
        representative_title=representative_title,
        representative_content=representative_content,
        articles=articles,
        max_articles=max(7, int(target_lines) + 3),
    )

    source_texts: List[str] = []
    keyword_texts: List[str] = []
    title_fallbacks: List[str] = []
    title_sentence_fallbacks: List[str] = []
    for article in picked_articles:
        title = _clean_title_text(article.get("title", "") or "")
        content = sanitize_summary_source_text(article.get("content", "") or "", title=title)
        if title:
            title_fallbacks.append(title)
            keyword_texts.append(title)
            title_sentence = _title_to_complete_sentence(title)
            if title_sentence:
                title_sentence_fallbacks.append(title_sentence)
        if summary_source_usable(title, content):
            source_texts.append(content)
            keyword_texts.append(f"{title} {content[:400]}")

    keywords = clean_review_keywords(
        keywords=extract_keywords(keyword_texts, topk=6),
        representative_title=representative_title,
        summary_lines=[],
        max_k=6,
        min_k=REVIEW_KEYWORD_MIN_K,
    )
    priority_title_lines = build_priority_title_summary_lines(
        representative_title=representative_title,
        articles=picked_articles,
        max_lines=min(int(URGENT_TITLE_MAX_LINES), int(target_lines)),
    )

    headline_lines = []
    if int(SUMMARY_SHORT_HEADLINE_LINES) > 0:
        headline_lines = build_headline_summary_lines(
            representative_title=representative_title,
            articles=picked_articles,
            max_lines=min(int(SUMMARY_SHORT_HEADLINE_LINES), int(target_lines)),
            max_chars=SUMMARY_SHORT_MAX_CHARS,
        )

    content_budget = max(2, int(target_lines) - len(headline_lines))
    content_min_lines = max(3, min(int(SUMMARY_SHORT_MIN_LINES), content_budget))
    content_candidate_budget = max(int(target_lines) * 3, int(content_budget) + 4)
    content_candidate_budget = min(content_candidate_budget, 16)
    content_lines = extractive_news_style_summary(
        source_texts if source_texts else title_sentence_fallbacks,
        max_lines=content_candidate_budget,
        min_lines=content_min_lines,
    )
    content_lines = refine_summary_lines_by_focus(
        content_lines,
        representative_title=representative_title,
        keywords=keywords,
        max_lines=content_budget,
        min_lines=content_min_lines,
    )
    lines = complete_summary_lines(
        content_lines,
        max_lines=target_lines,
        soft_max_chars=SUMMARY_COMPLETE_SOFT_MAX_CHARS,
        hard_max_chars=SUMMARY_COMPLETE_HARD_MAX_CHARS,
    )

    if len(lines) < int(SUMMARY_SHORT_MIN_LINES) and stored_short_summary:
        lines = complete_summary_lines(
            lines + complete_summary_lines(
                stored_short_summary,
                max_lines=target_lines,
                soft_max_chars=SUMMARY_COMPLETE_SOFT_MAX_CHARS,
                hard_max_chars=SUMMARY_COMPLETE_HARD_MAX_CHARS,
            ),
            max_lines=target_lines,
            soft_max_chars=SUMMARY_COMPLETE_SOFT_MAX_CHARS,
            hard_max_chars=SUMMARY_COMPLETE_HARD_MAX_CHARS,
        )
    if len(lines) < int(SUMMARY_SHORT_MIN_LINES) and source_texts:
        lines = complete_summary_lines(
            lines + complete_summary_lines(
                source_texts,
                max_lines=max(int(target_lines) + 2, int(SUMMARY_SHORT_MIN_LINES)),
                soft_max_chars=SUMMARY_COMPLETE_SOFT_MAX_CHARS,
                hard_max_chars=SUMMARY_COMPLETE_HARD_MAX_CHARS,
            ),
            max_lines=target_lines,
            soft_max_chars=SUMMARY_COMPLETE_SOFT_MAX_CHARS,
            hard_max_chars=SUMMARY_COMPLETE_HARD_MAX_CHARS,
        )
    if len(lines) < int(SUMMARY_SHORT_MIN_LINES) and title_sentence_fallbacks:
        lines = complete_summary_lines(
            lines + title_sentence_fallbacks,
            max_lines=target_lines,
            soft_max_chars=SUMMARY_COMPLETE_SOFT_MAX_CHARS,
            hard_max_chars=SUMMARY_COMPLETE_HARD_MAX_CHARS,
        )
    if len(lines) < int(SUMMARY_SHORT_MIN_LINES) and representative_title:
        rep_sentence = _title_to_complete_sentence(representative_title)
        if rep_sentence:
            lines = complete_summary_lines(
                lines + [rep_sentence],
                max_lines=target_lines,
                soft_max_chars=SUMMARY_COMPLETE_SOFT_MAX_CHARS,
                hard_max_chars=SUMMARY_COMPLETE_HARD_MAX_CHARS,
            )

    preferred_opening_lines = priority_title_lines
    lines = _normalize_complete_summary_output(preferred_opening_lines + lines, max_lines=target_lines)
    if len(lines) < int(SUMMARY_SHORT_MIN_LINES) and title_sentence_fallbacks:
        lines = _normalize_complete_summary_output(
            preferred_opening_lines + lines + title_sentence_fallbacks,
            max_lines=target_lines,
        )
    if len(lines) < int(SUMMARY_SHORT_MIN_LINES) and representative_title:
        rep_sentence = _title_to_complete_sentence(representative_title)
        if rep_sentence:
            lines = _normalize_complete_summary_output(
                preferred_opening_lines + lines + [rep_sentence],
                max_lines=target_lines,
            )

    return "\n".join(lines).strip()

def _best_consensus_title(candidate_titles: List[str], keywords: List[str]) -> str:
    cleaned: List[str] = []
    seen: set = set()
    for raw in (candidate_titles or []):
        t = _clean_title_text(raw)
        if len(t) < 6:
            continue
        k = t.lower()
        if k in seen:
            continue
        seen.add(k)
        cleaned.append(t)
    if not cleaned:
        return ""

    kw_set: set = set()
    for kw in (keywords or []):
        for tok in TOKEN_RE.findall(str(kw).lower()):
            if not is_noise_keyword(tok):
                kw_set.add(tok)

    token_sets: List[set] = []
    token_freq: Dict[str, int] = {}
    for t in cleaned:
        toks = _title_token_set(t)
        token_sets.append(toks)
        for tok in toks:
            token_freq[tok] = int(token_freq.get(tok, 0)) + 1

    best_i = 0
    best_score = -1e9
    for i, t in enumerate(cleaned):
        toks = token_sets[i]
        kw_hit = len(toks & kw_set)
        consensus = sum(token_freq.get(tok, 0) for tok in toks)
        length_penalty = abs(len(t) - 34) / 34.0
        score = (3.0 * kw_hit) + (1.0 * consensus) - (0.8 * length_penalty)
        # source_title is appended first in compose_issue_title(); keep a mild stability bias
        if i == 0:
            score += 0.4
        if len(t) > 72:
            score -= 1.5
        if "[" in t or "]" in t:
            score -= 1.0
        if score > best_score or (abs(score - best_score) < 1e-9 and len(t) < len(cleaned[best_i])):
            best_score = score
            best_i = i
    return cleaned[best_i]

def compose_issue_title(
    source_title: str,
    keywords: List[str],
    summary_lines: List[str],
    max_chars: int = 64,
    candidate_titles: Optional[List[str]] = None
) -> str:
    candidates: List[str] = []
    if source_title:
        candidates.append(str(source_title))
    for t in (candidate_titles or []):
        candidates.append(str(t))
    base = _best_consensus_title(candidates, keywords)
    if not base:
        base = _clean_title_text(source_title)

    if not base:
        for ln in (summary_lines or []):
            txt = str(ln).lstrip("- ").strip()
            txt = normalize_text(txt)
            txt = re.split(r"[.?!]\s+|;\s+|:\s+", txt, maxsplit=1)[0].strip()
            txt = re.sub(r"\s+", " ", txt).strip(" -:")
            if len(txt) >= 8:
                base = txt
                break

    if not base:
        kw_parts: List[str] = []
        seen_kw: set = set()
        for kw in (keywords or []):
            k = normalize_text(str(kw))
            k = re.sub(r"\s+", " ", k).strip(" -:")
            if not k:
                continue
            lk = k.lower()
            if lk in seen_kw:
                continue
            seen_kw.add(lk)
            kw_parts.append(k)
            if len(kw_parts) >= 2:
                break
        base = (("·".join(kw_parts) + " 이슈") if kw_parts else "주요 이슈 업데이트")
    return _truncate_with_ellipsis(base, int(max_chars))

def to_kst_iso(ts_like: Any) -> str:
    ts = pd.to_datetime(ts_like, errors="coerce")
    if pd.isna(ts):
        return ""
    try:
        if getattr(ts, "tzinfo", None) is None:
            ts = ts.tz_localize(KST)
        else:
            ts = ts.tz_convert(KST)
        return ts.isoformat(timespec="seconds")
    except Exception:
        try:
            ts2 = pd.to_datetime(ts_like, errors="coerce", utc=True)
            if pd.isna(ts2):
                return ""
            return ts2.tz_convert(KST).isoformat(timespec="seconds")
        except Exception:
            return ""

