def normalize_text(s: str) -> str:
    s = s or ""
    s = EMAIL_RE.sub(" ", s)
    s = URL_RE.sub(" ", s)
    s = s.replace("\u200b", " ")
    s = BOILERPLATE_RE.sub(" ", s)
    s = WS_RE.sub(" ", s).strip()
    return s

def title_tokens(title: str) -> List[str]:
    toks = TOKEN_RE.findall((title or "").lower())
    return toks[:30]

def is_noise_keyword(tok: str) -> bool:
    t = (tok or "").strip().lower()
    if len(t) < 2:
        return True
    if t.isdigit():
        return True
    if t in KEYWORD_STOPWORDS:
        return True
    return False

def _strip_kw_particle(tok: str) -> str:
    t = (tok or "").strip().lower()
    if not t:
        return ""
    # Strip one or two trailing particles (e.g., "대통령은" -> "대통령").
    for _ in range(2):
        nt = KW_PARTICLE_RE.sub("", t)
        if nt == t:
            break
        t = nt
    return t

def normalize_keyword_candidate(term: str, max_tokens: int = 3) -> str:
    raw = normalize_text(html.unescape(str(term or ""))).lower()
    toks = TOKEN_RE.findall(raw)
    if not toks:
        return ""

    out: List[str] = []
    seen: set = set()
    for tok in toks:
        t = _strip_kw_particle(tok)
        if len(t) < 2:
            continue
        if t.isdigit():
            continue
        if DATE_LIKE_TOKEN_RE.match(t):
            continue
        if t in KEYWORD_EXTRACT_STOPWORDS:
            continue
        # Drop short verb-like forms that leak from sentence tails.
        if len(t) <= 6 and t.endswith(KEYWORD_VERBISH_ENDINGS):
            continue
        # Drop short verb-like tails that frequently pollute issue tags.
        if len(t) <= 4 and t.endswith(("했다", "한다", "됐다", "되는")):
            continue
        if t in seen:
            continue
        seen.add(t)
        out.append(t)
        if len(out) >= int(max_tokens):
            break

    if not out:
        return ""
    return " ".join(out)

def clean_review_keywords(
    keywords: List[str],
    representative_title: str,
    summary_lines: List[str],
    max_k: int = 6,
    min_k: int = REVIEW_KEYWORD_MIN_K
) -> List[str]:
    max_k = max(1, int(max_k))
    min_k = max(1, min(int(min_k), int(max_k)))
    focus_tokens = {t for t in title_tokens(representative_title) if not is_noise_keyword(t)}
    for ln in (summary_lines or []):
        for tok in TOKEN_RE.findall(str(ln).lower()):
            if not is_noise_keyword(tok):
                focus_tokens.add(tok)

    picked: List[str] = []
    seen: set = set()


    def _is_bad_tokens(toks: List[str]) -> bool:
        for t in toks:
            if t in REVIEW_KEYWORD_BLOCKLIST:
                return True
            if len(t) <= 5 and t.endswith(REVIEW_KEYWORD_BAD_SUFFIXES):
                return True
        return False

    def _try_add(raw_term: str, require_focus_for_single: bool = True) -> None:
        nk = normalize_keyword_candidate(str(raw_term), max_tokens=3)
        if not nk:
            return
        toks = [t for t in TOKEN_RE.findall(nk.lower()) if len(t) >= 2]
        if not toks:
            return
        if _is_bad_tokens(toks):
            return
        tok_set = set(toks)
        if require_focus_for_single and focus_tokens and len(tok_set) == 1 and not (tok_set & focus_tokens):
            return
        key = re.sub(r"\s+", "", nk.lower())
        if key in seen:
            return
        seen.add(key)
        picked.append(nk)

    # 1) strict pass
    for kw in (keywords or []):
        _try_add(kw, require_focus_for_single=True)
        if len(picked) >= int(max_k):
            return picked[: int(max_k)]

    # 2) relaxed pass when still short
    if len(picked) < int(min_k):
        for kw in (keywords or []):
            _try_add(kw, require_focus_for_single=False)
            if len(picked) >= int(min_k) or len(picked) >= int(max_k):
                break

    # 3) title/focus token backfill to satisfy minimum count with relevant tokens
    if len(picked) < int(min_k):
        for tok in title_tokens(representative_title):
            _try_add(tok, require_focus_for_single=False)
            if len(picked) >= int(min_k) or len(picked) >= int(max_k):
                break
    if len(picked) < int(min_k):
        for tok in sorted(focus_tokens):
            _try_add(tok, require_focus_for_single=False)
            if len(picked) >= int(min_k) or len(picked) >= int(max_k):
                break

    return picked[: int(max_k)]

def clean_html_text(value):
    if not value:
        return ""

    text = str(value)
    text = html.unescape(text)

    try:
        text = BeautifulSoup(text, "html.parser").get_text(" ", strip=True)
    except Exception:
        text = re.sub(r"<[^>]+>", " ", text)

    text = re.sub(r"\s+", " ", text).strip()
    return text

def clean_summary_text(value):
    if not value:
        return ""

    text = str(value)
    text = html.unescape(text)
    text = re.sub(r"(?i)<\s*br\s*/?\s*>", "\n", text)

    try:
        text = BeautifulSoup(text, "html.parser").get_text("\n", strip=True)
    except Exception:
        text = re.sub(r"<[^>]+>", " ", text)

    lines: List[str] = []
    for raw in re.split(r"\n+", text):
        s = re.sub(r"[ \t\r\f\v]+", " ", raw).strip()
        if s:
            lines.append(s)
    return "\n".join(lines)

def sanitize_summary_source_text(value, title: str = "") -> str:
    text = clean_html_text(value)
    if not text:
        return ""

    clean_title = normalize_text(title)
    if clean_title and text.startswith(clean_title):
        text = text[len(clean_title):].lstrip(" -:|")

    text = re.sub(r"^\[[^\]]{1,24}\]\s*", "", text)
    text = re.sub(r"^(?:[가-힣]{2,6}\s*기자\s*=?\s*)", "", text)
    text = re.sub(r"\s+", " ", text).strip()

    cut_at = None
    for marker in SUMMARY_TRIM_MARKERS:
        pos = text.find(marker)
        if pos >= 180:
            cut_at = pos if cut_at is None else min(cut_at, pos)

    noise_hits = list(SUMMARY_REPEAT_NOISE_RE.finditer(text))
    if len(noise_hits) >= 3:
        for hit in noise_hits[1:]:
            if hit.start() >= 260:
                cut_at = hit.start() if cut_at is None else min(cut_at, hit.start())
                break

    if cut_at is not None:
        text = text[:cut_at].rstrip(" -:|/,.;")

    return re.sub(r"\s+", " ", text).strip()

def summary_source_usable(title: str, content: str) -> bool:
    c = sanitize_summary_source_text(content, title=title)
    if len(c) < max(int(SUSP_MIN_CONTENT_CHARS), 80):
        return False
    toks = title_tokens(title)
    if not toks:
        return True
    head = c[: int(SUSP_HEAD_MAX_CHARS)].lower()
    hits = sum(1 for t in toks if t in head)
    need = int(SUSP_NEED_HITS_LONG if len(toks) >= 4 else SUSP_NEED_HITS_SHORT)
    return hits >= need

def _normalize_summary_candidate_text(text: str) -> str:
    s = clean_html_text(text)
    s = re.sub(r"^[\-\*\u2022\u25E6\u00B7]+\s*", "", s)
    s = SUMMARY_PREFIX_NOISE_RE.sub("", s).strip()
    s = SUMMARY_REPORTER_TAIL_RE.sub("", s).strip()
    s = re.sub(r"^(?:속보|단독)\s+", "", s).strip()
    return re.sub(r"\s+", " ", s).strip(" -:;,/|")

def _summary_probe_text(text: str) -> str:
    return _normalize_summary_candidate_text(text).strip(" \"'“”‘’.,!?()[]")

def _is_source_like_token(token: str) -> bool:
    t = re.sub(r"[^0-9A-Za-z가-힣]+", "", str(token or "").strip())
    if not t:
        return False
    folded = t.replace(" ", "").lower()
    if folded in SUMMARY_SOURCE_ONLY_EXACT:
        return True
    return bool(SUMMARY_SOURCE_TOKEN_RE.fullmatch(t))

def _is_source_only_summary_line(text: str) -> bool:
    probe = _summary_probe_text(text)
    if not probe:
        return True
    if SUMMARY_SOURCE_LINE_RE.match(probe):
        probe = SUMMARY_SOURCE_LINE_RE.sub("", probe).strip()
        if not probe:
            return True
    collapsed = re.sub(r"\s+", "", probe).lower()
    if collapsed in SUMMARY_SOURCE_ONLY_EXACT:
        return True
    toks = TOKEN_RE.findall(probe)
    if not toks or len(toks) > 3:
        return False
    return all(_is_source_like_token(tok) for tok in toks)

def _summary_content_tokens(text: str) -> List[str]:
    out: List[str] = []
    for tok in TOKEN_RE.findall((text or "").lower()):
        t = _strip_kw_particle(tok)
        if len(t) < 2:
            continue
        if t.isdigit():
            continue
        if DATE_LIKE_TOKEN_RE.match(t):
            continue
        if t in KEYWORD_STOPWORDS:
            continue
        if _is_source_like_token(t):
            continue
        out.append(t)
    return out

def _summary_line_usable(text: str, min_chars: int = SUMMARY_SHORT_MIN_CHARS) -> bool:
    s = _normalize_summary_candidate_text(text)
    if len(_summary_probe_text(s)) < int(min_chars):
        return False
    if "..." in s or "…" in s or "크게보기" in s:
        return False
    if any(phrase in s for phrase in SUMMARY_CAPTION_PHRASES):
        return False
    if any(phrase in s for phrase in SUMMARY_OFFTOPIC_PHRASES):
        return False
    if _is_source_only_summary_line(s):
        return False
    content_toks = _summary_content_tokens(s)
    if not content_toks:
        return False
    if len(_summary_probe_text(s)) < 22 and len(set(content_toks)) < 2:
        return False
    return True

def _summary_line_key(text: str) -> str:
    return re.sub(r"[^0-9A-Za-z가-힣]+", "", str(text or "").lower())

def _compact_summary_piece(text: str, max_chars: int) -> str:
    s = _normalize_summary_candidate_text(text)
    if len(_summary_probe_text(s)) < int(SUMMARY_SHORT_MIN_CHARS):
        return ""
    if not _summary_line_usable(s):
        return ""
    return _truncate_with_ellipsis(s, int(max_chars))

def _looks_complete_sentence(text: str) -> bool:
    s = str(text or "").strip()
    if not s:
        return False
    if "..." in s or "…" in s:
        return False
    return bool(SUMMARY_COMPLETE_END_RE.search(s))

def _strip_lead_fragment_before_date(text: str) -> str:
    s = str(text or "").strip()
    if not s:
        return ""
    match = re.search(r"\b\d{1,2}일\b", s)
    if not match or match.start() < 12:
        return s
    prefix = s[: match.start()].strip(" -:;,/")
    if not prefix:
        return s
    if re.search(r"[.!?。！？]$", prefix) or SUMMARY_COMPLETE_END_RE.search(prefix):
        return s
    return s[match.start():].lstrip(" -:;,/")

def _finalize_complete_sentence(text: str) -> str:
    s = str(text or "").strip().strip(" -:;,/")
    if not s:
        return ""
    if "..." in s or "…" in s or "크게보기" in s:
        return ""
    if any(phrase in s for phrase in SUMMARY_CAPTION_PHRASES):
        return ""
    if any(phrase in s for phrase in SUMMARY_OFFTOPIC_PHRASES):
        return ""
    if re.search(r"[.!?。！？][\"'”’)\]]*$", s):
        return s
    if SUMMARY_COMPLETE_END_RE.search(s):
        m = re.search(r"[\"'”’)\]]*$", s)
        if m:
            suffix = m.group(0)
            core = s[: len(s) - len(suffix)]
            return core.rstrip() + "." + suffix
        return s + "."
    return ""

def _complete_summary_piece(
    text: str,
    soft_max_chars: int = SUMMARY_COMPLETE_SOFT_MAX_CHARS,
    hard_max_chars: int = SUMMARY_COMPLETE_HARD_MAX_CHARS,
) -> str:
    s = _normalize_summary_candidate_text(text)
    s = _strip_lead_fragment_before_date(s)
    if len(_summary_probe_text(s)) < int(SUMMARY_SHORT_MIN_CHARS):
        return ""
    if not _summary_line_usable(s):
        return ""

    if len(s) <= int(soft_max_chars) and _looks_complete_sentence(s):
        finalized = _finalize_complete_sentence(s)
        return finalized if _summary_line_usable(finalized) else ""

    probe = s[: int(hard_max_chars)]
    candidates: List[str] = []
    for match in SUMMARY_COMPLETE_PREFIX_RE.finditer(probe):
        candidate = probe[: match.end()].strip(" -:;,/")
        if len(_summary_probe_text(candidate)) < int(SUMMARY_SHORT_MIN_CHARS):
            continue
        finalized = _finalize_complete_sentence(candidate)
        if finalized and _summary_line_usable(finalized):
            candidates.append(finalized)

    if candidates:
        within_soft = [c for c in candidates if len(c) <= int(soft_max_chars)]
        if within_soft:
            return within_soft[-1]
        return candidates[0]

    if len(s) <= int(hard_max_chars) and _looks_complete_sentence(s):
        finalized = _finalize_complete_sentence(s)
        return finalized if _summary_line_usable(finalized) else ""

    return ""

def complete_summary_lines(
    lines_or_text: Any,
    max_lines: int = SUMMARY_SHORT_MAX_LINES,
    soft_max_chars: int = SUMMARY_COMPLETE_SOFT_MAX_CHARS,
    hard_max_chars: int = SUMMARY_COMPLETE_HARD_MAX_CHARS,
) -> List[str]:
    raw_items: List[str] = []
    if isinstance(lines_or_text, (list, tuple)):
        raw_items = [str(x) for x in lines_or_text if str(x or "").strip()]
    else:
        raw = str(lines_or_text or "").strip()
        if raw:
            raw_items = [raw]

    if not raw_items:
        return []

    picked: List[str] = []
    seen_keys: List[str] = []

    def _push(candidate: str) -> None:
        if not candidate:
            return
        if not _summary_line_usable(candidate):
            return
        key = _summary_line_key(candidate)
        if len(key) < int(SUMMARY_SHORT_MIN_CHARS):
            return
        for prev in seen_keys:
            if key == prev:
                return
            if len(key) >= 18 and len(prev) >= 18 and (key in prev or prev in key):
                return
        seen_keys.append(key)
        picked.append("- " + candidate)

    for raw in raw_items:
        text = clean_summary_text(raw)
        if not text:
            continue
        for block in re.split(r"\n+", text):
            block = str(block or "").strip()
            if not block:
                continue
            bullet_parts = [p.strip() for p in SUMMARY_BULLET_SPLIT_RE.split(block) if p.strip()]
            if not bullet_parts:
                bullet_parts = [block]
            for part in bullet_parts:
                sentence_parts = [p.strip() for p in split_sentences_ko(part) if p.strip()]
                if not sentence_parts:
                    sentence_parts = [part]
                for sent in sentence_parts:
                    _push(
                        _complete_summary_piece(
                            sent,
                            soft_max_chars=soft_max_chars,
                            hard_max_chars=hard_max_chars,
                        )
                    )
                    if len(picked) >= int(max_lines):
                        return picked[: int(max_lines)]

    return picked[: int(max_lines)]

def compact_summary_lines(
    lines_or_text: Any,
    max_lines: int = SUMMARY_SHORT_MAX_LINES,
    max_chars: int = SUMMARY_SHORT_MAX_CHARS,
) -> List[str]:
    raw_items: List[str] = []
    if isinstance(lines_or_text, (list, tuple)):
        raw_items = [str(x) for x in lines_or_text if str(x or "").strip()]
    else:
        raw = str(lines_or_text or "").strip()
        if raw:
            raw_items = [raw]

    if not raw_items:
        return []

    picked: List[str] = []
    seen_keys: List[str] = []

    def _push(candidate: str) -> None:
        if not candidate:
            return
        if not _summary_line_usable(candidate):
            return
        key = _summary_line_key(candidate)
        if len(key) < int(SUMMARY_SHORT_MIN_CHARS):
            return
        for prev in seen_keys:
            if key == prev:
                return
            if len(key) >= 18 and len(prev) >= 18 and (key in prev or prev in key):
                return
        seen_keys.append(key)
        picked.append("- " + candidate)

    for raw in raw_items:
        text = clean_summary_text(raw)
        if not text:
            continue
        for block in re.split(r"\n+", text):
            block = str(block or "").strip()
            if not block:
                continue
            bullet_parts = [p.strip() for p in SUMMARY_BULLET_SPLIT_RE.split(block) if p.strip()]
            if not bullet_parts:
                bullet_parts = [block]
            for part in bullet_parts:
                sentence_parts = [p.strip() for p in SUMMARY_SENTENCE_SPLIT_RE.split(part) if p.strip()]
                if not sentence_parts:
                    sentence_parts = [part]
                for sent in sentence_parts:
                    _push(_compact_summary_piece(sent, max_chars=max_chars))
                    if len(picked) >= int(max_lines):
                        return picked[: int(max_lines)]

    if picked:
        return picked[: int(max_lines)]

    for raw in raw_items:
        candidate = _compact_summary_piece(raw, max_chars=max_chars)
        if candidate:
            _push(candidate)
        if len(picked) >= int(max_lines):
            break
    return picked[: int(max_lines)]

def compact_short_summary_text(
    lines_or_text: Any,
    max_lines: int = SUMMARY_SHORT_MAX_LINES,
    max_chars: int = SUMMARY_SHORT_MAX_CHARS,
) -> str:
    return "\n".join(
        compact_summary_lines(
            lines_or_text,
            max_lines=max_lines,
            max_chars=max_chars,
        )
    ).strip()

def _extract_geo_tokens(text: str) -> set:
    toks = TOKEN_RE.findall((text or "").lower())
    out: set = set()
    for tok in toks:
        t = (tok or "").strip()
        if len(t) < 2:
            continue
        if t in GEO_CORE_TOKENS:
            out.add(t)
            continue
        if t.endswith(GEO_SUFFIXES):
            out.add(t)
    return out

def _is_local_incident_cluster(titles: List[str]) -> bool:
    tok_set: set = set()
    for t in titles:
        tok_set.update(title_tokens(t))
    return any(t in LOCAL_INCIDENT_TOKENS for t in tok_set)

def prune_geo_mismatch_members(
    members: List[int],
    titles: List[str],
    rep_idx: int,
    min_keep: int = 2
) -> Tuple[List[int], List[int]]:
    if len(members) < 3:
        return members, []

    cluster_titles = [str(titles[i]) for i in members]
    if not _is_local_incident_cluster(cluster_titles):
        return members, []

    geo_map: Dict[int, set] = {}
    freq: Dict[str, int] = {}
    for i in members:
        gs = _extract_geo_tokens(str(titles[i]))
        geo_map[i] = gs
        for g in gs:
            freq[g] = int(freq.get(g, 0) + 1)

    if not freq:
        return members, []

    anchor_min = max(2, int(math.ceil(len(members) * 0.35)))
    anchors = [g for g, c in sorted(freq.items(), key=lambda kv: (-kv[1], kv[0])) if c >= anchor_min]
    if not anchors:
        return members, []
    anchor_set = set(anchors[:2])

    rep_title = str(titles[rep_idx])
    kept: List[int] = []
    dropped: List[int] = []
    for i in members:
        gs = geo_map.get(i, set())
        if gs and (gs & anchor_set):
            kept.append(i)
            continue
        if title_jaccard(str(titles[i]), rep_title) >= 0.18:
            kept.append(i)
            continue
        dropped.append(i)

    if len(kept) < int(min_keep):
        return members, []
    return kept, dropped

def content_suspicious(title: str, content: str, cfg: PipelineConfig) -> bool:
    _ = cfg
    return not summary_source_usable(title, content)

def drop_suspicious_rows(df: pd.DataFrame, cfg: PipelineConfig) -> Tuple[pd.DataFrame, int]:
    if df is None or len(df) == 0 or (not cfg.DROP_SUSPICIOUS_ROWS):
        return df, 0
    keep = []
    for t, c in zip(df["title"].astype(str), df["content"].astype(str)):
        keep.append(not content_suspicious(t, c, cfg))
    dropped = int((~pd.Series(keep)).sum())
    out = df.loc[keep].reset_index(drop=True)
    return out, dropped

