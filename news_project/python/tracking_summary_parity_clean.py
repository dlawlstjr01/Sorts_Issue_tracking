def dedup_articles(df: pd.DataFrame, cfg: PipelineConfig) -> Tuple[pd.DataFrame, int, int]:
    if df is None or len(df) == 0:
        return df, 0, 0
    df = df.copy()
    df["_dedup_key"] = [row_dedup_key(u, t, c) for u, t, c in zip(df["url"].astype(str), df["title"].astype(str), df["content"].astype(str))]
    df["_clen"] = df["content"].astype(str).str.len()
    df = df.sort_values(["_dt","_clen"], ascending=[False, False], kind="mergesort")
    before = len(df)
    df = df.drop_duplicates(subset=["_dedup_key"], keep="first").reset_index(drop=True)
    strict_dropped = before - len(df)
    df = df.drop(columns=["_dedup_key","_clen"], errors="ignore")

    minhash_dropped = 0
    if cfg.DEDUP_USE_MINHASH and len(df) > 1:
        try:
            num_perm = 64
            lsh = MinHashLSH(threshold=float(cfg.DEDUP_SIM_THRESHOLD), num_perm=num_perm)
            keep = []
            for i, (t, c) in enumerate(zip(df["title"].astype(str), df["content"].astype(str))):
                text = (t + " " + c)[:10000]
                toks = TOKEN_RE.findall(text.lower())
                if len(toks) < 8:
                    keep.append(True)
                    continue
                mh = MinHash(num_perm=num_perm)
                for w in set(toks):
                    mh.update(w.encode("utf-8"))
                hits = lsh.query(mh)
                if hits:
                    keep.append(False)
                    continue
                lsh.insert(str(i), mh)
                keep.append(True)
            before2 = len(df)
            df = df.loc[keep].reset_index(drop=True)
            minhash_dropped = before2 - len(df)
        except Exception as e:
            print("[WARN] MinHash dedup failed; keep strict only:", repr(e))
    return df, int(strict_dropped), int(minhash_dropped)

