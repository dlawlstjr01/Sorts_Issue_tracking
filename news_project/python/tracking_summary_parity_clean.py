def iter_input_sources(path: str) -> Iterable[Tuple[str, Dict[str,str]]]:
    p = Path(path)
    if p.is_file() and p.suffix.lower() == ".zip":
        zp = str(p)
        with zipfile.ZipFile(zp, "r") as z:
            for name in z.namelist():
                if name.lower().endswith(".csv"):
                    yield f"{p.name}:{name}", {"kind":"zip","zip_path":zp,"member":name}
        return
    if p.is_file():
        yield str(p), {"kind":"file","path":str(p)}
        return
    if p.is_dir():
        for fp in sorted(p.glob("*.csv")):
            yield str(fp), {"kind":"file","path":str(fp)}
        for fp in sorted(p.glob("*.zip")):
            zp = str(fp)
            with zipfile.ZipFile(zp, "r") as z:
                for name in z.namelist():
                    if name.lower().endswith(".csv"):
                        yield f"{fp.name}:{name}", {"kind":"zip","zip_path":zp,"member":name}
        return
    # Fallback pattern matching (supports absolute/relative patterns on Python 3.12).
    import glob
    for m in sorted(glob.glob(path)):
        mp = Path(m)
        if mp.is_file() and mp.suffix.lower() == ".zip":
            zp = str(mp)
            with zipfile.ZipFile(zp, "r") as z:
                for name in z.namelist():
                    if name.lower().endswith(".csv"):
                        yield f"{mp.name}:{name}", {"kind":"zip","zip_path":zp,"member":name}
            continue
        if mp.is_file():
            yield str(mp), {"kind":"file","path":str(mp)}
            continue
        if mp.is_dir():
            for fp in sorted(mp.glob("*.csv")):
                yield str(fp), {"kind":"file","path":str(fp)}
            for fp in sorted(mp.glob("*.zip")):
                zp = str(fp)
                with zipfile.ZipFile(zp, "r") as z:
                    for name in z.namelist():
                        if name.lower().endswith(".csv"):
                            yield f"{fp.name}:{name}", {"kind":"zip","zip_path":zp,"member":name}

def read_csv_chunks(source: Dict[str,str], chunksize: int, usecols: Optional[List[str]] = None) -> Iterable[pd.DataFrame]:
    kind = source.get("kind")
    if kind == "file":
        yield from pd.read_csv(source["path"], chunksize=chunksize, usecols=usecols, dtype=str, encoding_errors="ignore")
        return
    if kind == "zip":
        with zipfile.ZipFile(source["zip_path"], "r") as z:
            with z.open(source["member"], "r") as f:
                yield from pd.read_csv(f, chunksize=chunksize, usecols=usecols, dtype=str, encoding_errors="ignore")
        return
    raise ValueError(f"Unknown source kind: {kind}")

def count_buckets(cfg: PipelineConfig) -> Tuple[Dict[str,int], int]:
    counts: Dict[str,int] = {}
    dropped_no_date = 0
    for _name, h in iter_input_sources(cfg.CSV_PATH):
        for chunk in read_csv_chunks(h, cfg.READ_CHUNKSIZE, usecols=["date"]):
            if "date" not in chunk.columns:
                dropped_no_date += len(chunk)
                continue
            dts = pd.to_datetime(chunk["date"], errors="coerce", utc=True)
            miss = dts.isna()
            if miss.any():
                dts_miss = pd.to_datetime(chunk.loc[miss, "date"], errors="coerce")
                try:
                    if getattr(dts_miss.dt, "tz", None) is None:
                        dts_miss = dts_miss.dt.tz_localize(KST).dt.tz_convert("UTC")
                    else:
                        dts_miss = dts_miss.dt.tz_convert("UTC")
                except Exception:
                    dts_miss = pd.to_datetime(chunk.loc[miss, "date"], errors="coerce", utc=True)
                dts_miss = pd.to_datetime(dts_miss, errors="coerce", utc=True)
                dts.loc[miss] = dts_miss

            for v in dts:
                if pd.isna(v):
                    dropped_no_date += 1
                    continue
                ts = v.tz_convert(KST) if v.tzinfo is not None else v.tz_localize(KST)
                b = bucket_key_from_dt(ts, cfg.BUCKET)
                counts[b] = counts.get(b, 0) + 1
    return counts, dropped_no_date

def select_target_buckets(counts: Dict[str,int], cfg: PipelineConfig) -> List[str]:
    if cfg.TARGET_BUCKETS:
        return cfg.TARGET_BUCKETS
    keys = sorted(list(counts.keys()), reverse=True)
    return keys[: max(1, int(cfg.MAX_BUCKETS))]

def load_bucket_df(cfg: PipelineConfig, bucket_key: str, cache_dir: Path) -> Tuple[pd.DataFrame, Dict[str,int]]:
    rows = []
    stats = {"raw_rows":0, "dropped_no_date":0}
    out_path = cache_dir / f"stage0_raw_{bucket_key}.csv"
    if out_path.exists() and cfg.RESUME:
        try:
            df = pd.read_csv(out_path, dtype=str)
            df["_dt"] = pd.to_datetime(df["_dt"], errors="coerce")
            return df, stats
        except Exception:
            out_path.unlink(missing_ok=True)

    for _name, h in iter_input_sources(cfg.CSV_PATH):
        for chunk in read_csv_chunks(h, cfg.READ_CHUNKSIZE, usecols=None):
            stats["raw_rows"] += len(chunk)
            for c in REQUIRED_COLS:
                if c not in chunk.columns:
                    chunk[c] = ""
            dts = pd.to_datetime(chunk["date"], errors="coerce", utc=True)
            miss = dts.isna()
            if miss.any():
                dts_miss = pd.to_datetime(chunk.loc[miss, "date"], errors="coerce")
                try:
                    if getattr(dts_miss.dt, "tz", None) is None:
                        dts_miss = dts_miss.dt.tz_localize(KST).dt.tz_convert("UTC")
                    else:
                        dts_miss = dts_miss.dt.tz_convert("UTC")
                except Exception:
                    dts_miss = pd.to_datetime(chunk.loc[miss, "date"], errors="coerce", utc=True)
                dts_miss = pd.to_datetime(dts_miss, errors="coerce", utc=True)
                dts.loc[miss] = dts_miss

            keep_mask = []
            dt_keep = []
            for v in dts:
                if pd.isna(v):
                    keep_mask.append(False)
                    stats["dropped_no_date"] += 1
                    dt_keep.append(pd.NaT)
                    continue
                ts = v.tz_convert(KST) if v.tzinfo is not None else v.tz_localize(KST)
                b = bucket_key_from_dt(ts, cfg.BUCKET)
                ok = (b == bucket_key)
                keep_mask.append(ok)
                dt_keep.append(ts)
            if not any(keep_mask):
                continue

            sub = chunk.loc[keep_mask, REQUIRED_COLS].copy()
            sub["_dt"] = [dt_keep[i] for i, ok in enumerate(keep_mask) if ok]
            sub["domain"] = sub["url"].astype(str).apply(safe_domain)
            rows.append(sub)

            if sum(len(x) for x in rows) >= cfg.MAX_DOCS_PER_BUCKET:
                break

    df = pd.concat(rows, ignore_index=True) if rows else pd.DataFrame(columns=REQUIRED_COLS + ["_dt","domain"])
    df.to_csv(out_path, index=False, encoding="utf-8-sig")
    return df, stats

