class UnionFind:
    def __init__(self, n: int):
        self.p = list(range(n))
        self.r = [0]*n
    def find(self, x: int) -> int:
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]
            x = self.p[x]
        return x
    def union(self, a: int, b: int) -> None:
        ra, rb = self.find(a), self.find(b)
        if ra == rb: return
        if self.r[ra] < self.r[rb]:
            self.p[ra] = rb
        elif self.r[ra] > self.r[rb]:
            self.p[rb] = ra
        else:
            self.p[rb] = ra
            self.r[ra] += 1
    def groups(self) -> Dict[int, List[int]]:
        g: Dict[int, List[int]] = {}
        for i in range(len(self.p)):
            r = self.find(i)
            g.setdefault(r, []).append(i)
        return g

def title_jaccard(a: str, b: str) -> float:
    sa = set(title_tokens(a))
    sb = set(title_tokens(b))
    if not sa or not sb:
        return 0.0
    return len(sa & sb) / max(1, len(sa | sb))

def text_token_jaccard(a: str, b: str, max_tok: int = 120) -> float:
    ta = TOKEN_RE.findall((a or "").lower())[:max_tok]
    tb = TOKEN_RE.findall((b or "").lower())[:max_tok]
    sa, sb = set(ta), set(tb)
    if not sa or not sb:
        return 0.0
    return len(sa & sb) / max(1, len(sa | sb))

def compute_cluster_metrics(members: List[int], emb: np.ndarray, rep_idx: int, sample_pairs: int = 200) -> Dict[str, float]:
    if len(members) == 0:
        return {"centroid_mean": 0.0, "rep_mean": 0.0, "rep_min": 0.0, "intra_sample_mean": 0.0}
    m = np.array(members, dtype=int)
    E = emb[m]
    centroid = l2_normalize_rows(E.mean(axis=0, keepdims=True))
    centroid_mean = float((E @ centroid.T).mean())
    rep = emb[rep_idx:rep_idx+1]
    rep_mean = float((E @ rep.T).mean())
    rep_min = float(np.min(E @ rep.T)) if len(members) > 0 else 0.0

    intra = 0.0
    if len(m) >= 2:
        rng = np.random.default_rng(123)
        pairs = min(sample_pairs, len(m)*(len(m)-1)//2)
        s = 0.0
        for _ in range(pairs):
            i, j = rng.choice(len(m), size=2, replace=False)
            s += float(E[i] @ E[j])
        intra = s / max(1, pairs)
    return {"centroid_mean": centroid_mean, "rep_mean": rep_mean, "rep_min": rep_min, "intra_sample_mean": intra}

def pick_representative(members: List[int], emb: np.ndarray) -> int:
    if len(members) == 1:
        return members[0]
    m = np.array(members, dtype=int)
    E = emb[m]
    centroid = E.mean(axis=0)
    centroid = centroid / (np.linalg.norm(centroid) + 1e-9)
    sims = E @ centroid
    return int(m[int(np.argmax(sims))])

def ordered_by_centroid(members: List[int], emb: np.ndarray) -> List[int]:
    m = np.array(members, dtype=int)
    E = emb[m]
    centroid = E.mean(axis=0)
    centroid = centroid / (np.linalg.norm(centroid) + 1e-9)
    sims = E @ centroid
    order = list(m[np.argsort(-sims)])
    return [int(x) for x in order]

def knn_edges_cos(E: np.ndarray, idxs: np.ndarray, topk: int, th: float) -> List[Tuple[int,int]]:
    edges = []
    sub = E[idxs]
    n = sub.shape[0]
    if n <= 1:
        return edges
    for i0 in range(0, n, 512):
        A = sub[i0:i0+512]
        S = A @ sub.T
        for bi in range(S.shape[0]):
            i = i0 + bi
            row = S[bi]
            row[i] = -1.0
            k = min(topk, n-1)
            cand = np.argpartition(-row, k)[:k]
            for j in cand:
                if row[j] >= th:
                    edges.append((int(idxs[i]), int(idxs[j])))
    return edges

def cluster_domain_then_merge(
    emb: np.ndarray,
    titles: List[str],
    domain_keys: List[str],
    broad_cats: List[str],
    lead_texts: List[str],
    cfg: PipelineConfig
) -> Dict[int, List[int]]:
    n = emb.shape[0]
    uf = UnionFind(n)
    E = emb

    dom2idx: Dict[str, List[int]] = {}
    for i, d in enumerate(domain_keys):
        dom2idx.setdefault(d or "", []).append(i)

    # within domain||bcat
    for d, idx_list in dom2idx.items():
        if len(idx_list) <= 1:
            continue
        idxs = np.array(idx_list, dtype=int)
        edges = knn_edges_cos(E, idxs, topk=int(cfg.KNN_MAX_NEIGHBORS), th=float(cfg.IN_DOMAIN_COS_TH))
        for a, b in edges:
            if title_jaccard(titles[a], titles[b]) < float(cfg.IN_DOMAIN_TITLE_JACC_TH):
                continue
            uf.union(a, b)

    groups = uf.groups()
    roots = list(groups.keys())
    centroids = []
    reps = []
    for r in roots:
        mem = groups[r]
        E0 = E[np.array(mem, dtype=int)]
        c = E0.mean(axis=0)
        c = c / (np.linalg.norm(c) + 1e-9)
        centroids.append(c)
        reps.append(pick_representative(mem, E))

    C = np.vstack(centroids).astype(np.float32) if centroids else np.zeros((0, E.shape[1]), np.float32)

    # cross-domain merge: stricter guard to prevent unrelated mixed issues
    if len(roots) >= 2:
        topm = min(60, len(roots)-1)
        S = C @ C.T
        np.fill_diagonal(S, -1.0)
        for i in range(len(roots)):
            row = S[i]
            cand = np.argpartition(-row, topm)[:topm]
            for j in cand:
                if row[j] < float(cfg.CROSS_DOMAIN_COS_TH):
                    continue
                ri = reps[i]
                rj = reps[j]
                if bool(getattr(cfg, "MERGE_REQUIRE_SAME_BROAD_CAT", True)):
                    bi = (broad_cats[ri] or "unknown").strip().lower()
                    bj = (broad_cats[rj] or "unknown").strip().lower()
                    if not bool(getattr(cfg, "CROSS_DOMAIN_ALLOW_UNKNOWN_BCAT", False)):
                        if bi == "unknown" or bj == "unknown":
                            continue
                    if bi != bj:
                        continue
                tj = title_jaccard(titles[ri], titles[rj])
                lt = text_token_jaccard(lead_texts[ri], lead_texts[rj], max_tok=140)
                allow_merge = False
                if tj >= float(cfg.TITLE_JACC_TH) and lt >= float(getattr(cfg, "CROSS_DOMAIN_LEAD_JACC_TH", 0.08)):
                    allow_merge = True
                elif row[j] >= float(getattr(cfg, "CROSS_DOMAIN_STRONG_COS_TH", 0.93)):
                    if tj >= float(cfg.TITLE_JACC_TH) or lt >= float(getattr(cfg, "CROSS_DOMAIN_LEAD_JACC_TH", 0.08)):
                        allow_merge = True
                if allow_merge:
                    uf.union(ri, rj)

    return uf.groups()

def cluster_with_lsh_cosine(emb: np.ndarray, texts: List[str], cfg: PipelineConfig) -> Dict[int, List[int]]:
    n = emb.shape[0]
    uf = UnionFind(n)
    num_perm = 128
    lsh = MinHashLSH(threshold=float(cfg.MINHASH_TH), num_perm=num_perm)

    mhs: List[Optional[MinHash]] = [None]*n
    for i, text in enumerate(tqdm(texts, desc="minhash", leave=False)):
        toks = TOKEN_RE.findall((text or "").lower())
        mh = MinHash(num_perm=num_perm)
        if not toks:
            mh.update(str(i).encode("utf-8"))
        else:
            for w in set(toks[:4000]):
                mh.update(w.encode("utf-8"))
        mhs[i] = mh
        lsh.insert(str(i), mh)

    for i in tqdm(range(n), desc="lsh-union", leave=False):
        mh = mhs[i]
        if mh is None:
            continue
        cand = lsh.query(mh)
        if len(cand) <= 1:
            continue
        vi = emb[i]
        for s in cand:
            j = int(s)
            if j <= i:
                continue
            if float(vi @ emb[j]) >= float(cfg.COS_TH):
                uf.union(i, j)
    return uf.groups()

