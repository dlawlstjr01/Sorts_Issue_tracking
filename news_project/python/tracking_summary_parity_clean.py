                where_clauses.append(
                    """
                    EXISTS (
                        SELECT 1
                        FROM issue_summary_articles f
                        WHERE f.issue_summary_id = s.id
                          AND f.article_id = %s
                    )
                    """
                )
                params.append(int(article_id))

